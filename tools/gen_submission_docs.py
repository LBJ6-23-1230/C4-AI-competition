def setup(doc: Document) -> None:
    st = doc.styles["Normal"]
    st.font.name = CN
    st.font.size = Pt(10.5)
    st.element.rPr.rFonts.set(qn("w:eastAsia"), CN)
    for i, size in ((1, 18), (2, 14), (3, 12)):
        h = doc.styles["Heading %d" % i]
        h.font.name = CN
        h.font.size = Pt(size)
        h.font.color.rgb = RGBColor(0x1F, 0x3A, 0x5F)
        h.element.rPr.rFonts.set(qn("w:eastAsia"), CN)
    for sec in doc.sections:
        sec.left_margin = sec.right_margin = Cm(2.2)
        sec.top_margin = sec.bottom_margin = Cm(2.0)


def h(doc, text, level=1):
    doc.add_heading(text, level=level)


def p(doc, text, bold=False, italic=False, size=None, align=None):
    par = doc.add_paragraph()
    run = par.add_run(text)
    run.bold = bold
    run.italic = italic
    if size:
        run.font.size = Pt(size)
    if align:
        par.alignment = align
    return par


def bullet(doc, text, level=0):
    par = doc.add_paragraph(text, style="List Bullet")
    if level:
        par.paragraph_format.left_indent = Cm(0.75 * (level + 1))
    return par


def table(doc, rows, widths=None):
    t = doc.add_table(rows=0, cols=len(rows[0]))
    t.style = "Light Grid Accent 1"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for row in rows:
        cells = t.add_row().cells
        for i, value in enumerate(row):
            cells[i].text = str(value)
            for par in cells[i].paragraphs:
                for run in par.runs:
                    run.font.size = Pt(9.5)
                    run.font.name = CN
                    run.element.rPr.rFonts.set(qn("w:eastAsia"), CN)
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    return t


def page_break(doc):
    doc.add_page_break()


